// 앱 프리셋 목록 (편곡 AI가 같은 이름으로 생각하게)
export function presetBrief() {
  const line = (mode) => PROGRESSIONS[mode].map((p) => `${p.name} [${p.degrees.join(',')}]${p.seventh ? '+7th' : ''} (${p.use})`).join(' / ');
  return `앱의 코드 진행 프리셋 (장조): ${line('major')}\n앱의 코드 진행 프리셋 (단조): ${line('minor')}`;
}

